export function linkOf(campaign: Campaign): string {
  const s = campaign.slug || campaign.id;
  return `kred.link/${s}/you`;
}

export function plainPay(campaign: Campaign): string {
  return `$${campaign.price} per verified install`;
}

export function usd(num: number): string {
  return '$' + num.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

export function fmtNum(n: number): string {
  return Math.round(n).toLocaleString('en-US');
}

export function getCampaignStats(campaign: Campaign): CampaignStats {
  const p = parseFloat(campaign.price) || 2.0;
  const baseInstalls = campaign.creators * 8;
  return {
    days: [12, 18, 22, 15, 29, 34, 40],
    inst: baseInstalls,
    clicks: Math.round(baseInstalls * 4.2),
    conv: 24,
    earned: Math.round(baseInstalls * p),
  };
}
